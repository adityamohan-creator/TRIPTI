#!/usr/bin/env node
/**
 * Bundles the migrations into the fewest copy-paste blocks the SQL Editor allows.
 *
 *   npm run db:bundle
 *
 * The split is not cosmetic. `0002_roles.sql` runs `ALTER TYPE ... ADD VALUE
 * 'ngo'`, and Postgres refuses to *use* a new enum value until the transaction
 * that added it has committed. `0003` and `0004` both reference 'ngo' in policy
 * expressions, which are evaluated when the policy is created — so they must run
 * in a later transaction or the whole script fails with:
 *
 *   unsafe use of new value "ngo" of enum type user_role
 *
 * Step 1 can safely include 0001 alongside 0002: the enum is created in that
 * same transaction, and the only value 0002 *uses* is 'citizen', which is a
 * rename of an existing value rather than a new one.
 *
 * Output is generated, gitignored, and always rebuilt from the migrations —
 * there is one source of truth and it is supabase/migrations/.
 */

import { mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const migrationsDir = join(root, 'supabase', 'migrations')
const outDir = join(root, 'supabase', 'bundle')

const STEPS = [
  {
    file: 'step-1.sql',
    includes: ['0001_init.sql', '0002_roles.sql'],
    note: 'Run this first. Let it finish before running step 2 — step 2 uses the enum value this one adds.',
  },
  {
    file: 'step-2.sql',
    includes: [
      '0003_auth_and_integrity.sql',
      '0004_operations.sql',
      '0005_extraction_provenance.sql',
    ],
    note: 'Run this only after step 1 has completed successfully.',
  },
  {
    file: 'step-3.sql',
    includes: ['0006_response_plans.sql'],
    note: 'Response plans and reservations. Safe to run on its own if steps 1 and 2 are already applied.',
  },
]

const available = readdirSync(migrationsDir).filter((f) => f.endsWith('.sql'))
const bundled = new Set(STEPS.flatMap((s) => s.includes))

// A migration added later that nobody wired into a step would be silently
// skipped by anyone following the bundle, so fail loudly instead.
const orphans = available.filter((f) => !bundled.has(f))
if (orphans.length > 0) {
  console.error(
    `These migrations are not in any bundle step: ${orphans.join(', ')}\n` +
      'Add them to STEPS in scripts/bundle-migrations.mjs.',
  )
  process.exit(1)
}

mkdirSync(outDir, { recursive: true })

for (const step of STEPS) {
  const body = step.includes
    .map((name) => {
      const sql = readFileSync(join(migrationsDir, name), 'utf8')
      return `-- ${'='.repeat(66)}\n-- ${name}\n-- ${'='.repeat(66)}\n\n${sql.trim()}\n`
    })
    .join('\n\n')

  const header = [
    '-- Generated by scripts/bundle-migrations.mjs — do not edit.',
    '-- Source of truth is supabase/migrations/.',
    `--`,
    `-- ${step.note}`,
    '',
    '',
  ].join('\n')

  writeFileSync(join(outDir, step.file), header + body, 'utf8')
  console.log(`  supabase/bundle/${step.file}  (${step.includes.join(' + ')})`)
}

console.log(
  '\nPaste step-1.sql into the Supabase SQL Editor and run it, then step-2.sql.',
)
